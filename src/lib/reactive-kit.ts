import { buildReactiveRequest, reactiveBrief, reactiveReport } from "./reactive-ai";
import type { z } from "zod";

type ReactiveReport = z.infer<typeof reactiveReport>;
type GenerateReport = (request: ReturnType<typeof buildReactiveRequest>) => Promise<unknown>;

export async function generateReactiveKit(raw: unknown, generate: GenerateReport): Promise<ReactiveReport> {
  const result = await generate(buildReactiveRequest(raw));
  return reactiveReport.parse(result);
}

export function buildReactiveDemo(raw: unknown): ReactiveReport {
  const brief = reactiveBrief.parse(raw);
  const offer = brief.offer.slice(0, 160);
  const greeting = { friendly: "Привет!", professional: "Здравствуйте.", concise: "" }[brief.tone];
  const variants = [
    {
      segment: "Запрашивали расчёт",
      messages: [
        `Актуален ли ещё вопрос по предложению «${offer}»?`,
        "Что изменилось с прошлого обсуждения? Подскажу, что стоит уточнить в расчёте.",
        "Если сравниваете варианты, могу объяснить, что входит в наш расчёт.",
        "Есть ли один вопрос по смете, на который пока не нашли ответа?",
        "Если вопрос больше не актуален, просто скажите. Я закрою обсуждение.",
      ],
    },
    {
      segment: "Отложили решение",
      messages: [
        `Возвращались к вопросу «${offer}» или планы пока отложены?`,
        "Если удобнее вернуться позже, подскажите, когда уместно написать.",
        "Могу прислать короткий список того, что полезно подготовить к выбору.",
        "Если планы изменились, обсудим только то, что актуально сейчас.",
        "Предлагаю поставить обсуждение на паузу. Возобновим его, если напишете сами.",
      ],
    },
    {
      segment: "Интересовались без расчёта",
      messages: [
        `Остались вопросы по теме «${offer}»? Могу сориентировать по вариантам.`,
        "Что сейчас важнее при выборе: состав работ, сроки или бюджет?",
        "Могу подсказать, какие параметры нужны для первого расчёта.",
        "Есть ли условие, без которого вариант точно не подойдёт?",
        "Если пока не до этого, закрою вопрос. Можете вернуться, когда будет удобно.",
      ],
    },
  ];
  const goals = ["Уточнить актуальность", "Выяснить контекст", "Дать полезную подсказку", "Снять неопределённость", "Завершить диалог"];
  const pause = "Пауза. Проверь ответы и ничего не отправляй без повода.";
  const days = [
    "Проверь согласия, список отказов и актуальность предложения. Раздели контакты на сегменты.",
    "Проверь один вариант сообщения на небольшой выборке с подтверждённым согласием.",
    pause,
    "Ответь тем, кто написал. Уточни один вопрос и не начинай рассылку по всей базе.",
    pause,
    "Проверь ответы и исключи неактуальные контакты.",
    pause,
    "Сравни реакции по сегментам и скорректируй шаблоны.",
    pause,
    "Предложи следующий шаг тем, кто подтвердил интерес.",
    pause,
    "Закрой обсуждения по просьбам клиентов и зафиксируй исход.",
    pause,
    "Подведи итоги. Сохрани обезличенные цифры и примеры удачных формулировок.",
  ];
  const oldContact = brief.lastContact === "older" || brief.lastContact === "quarter";
  return reactiveReport.parse({
    segments: variants.map(({ segment }) => segment),
    messages: variants.flatMap(({ segment, messages }) => messages.map((text, index) => ({
      goal: goals[index], channel: "Согласованный канал", segment,
      text: [greeting, text].filter(Boolean).join(" "),
    }))),
    schedule: days.map((action, i) => ({
      day: i + 1,
      action: i === 1 && oldContact ? "Для давних контактов сначала проверь актуальность согласия. При сомнении не отправляй." : action,
      stopCondition: "При отказе, отзыве согласия или его отсутствии не отправляй. Без реакции придерживайся паузы.",
    })),
    objections: [
      { objection: "Дорого", answer: "Уточни, какую часть сравнивают. Объясни состав работ и покажи отличия без обещания скидки." },
      { objection: "Пока не актуально", answer: "Подтверди паузу. Дату следующего контакта согласуй только по инициативе клиента." },
      { objection: "Не хватает времени", answer: "Предложи короткий ответ в выбранном клиентом канале." },
      { objection: "Уже выбрали другого", answer: "Поблагодари за ответ и закрой обсуждение." },
      { objection: "Нужно подумать", answer: "Уточни, какой информации не хватает для решения." },
      { objection: "Нет доверия", answer: "Покажи проверяемые материалы по запросу. Не выдумывай отзывы и гарантии." },
      { objection: "Не ясно, что входит", answer: "Перечисли только реально включённые работы и отдельные позиции." },
      { objection: "Больше не пишите", answer: "Прекрати контакты и зафиксируй отказ в списке исключений." },
    ],
    offers: [
      `Уточнить требования к предложению «${offer}».`,
      "Помочь сравнить состав и условия вариантов без выдуманной скидки.",
      brief.permittedOffer ? `Разрешённый вариант из анкеты: ${brief.permittedOffer}` : "Проверить, нужен ли обновлённый расчёт.",
    ],
    metrics: ["Сегмент", "Согласие", "Попытка контакта", "Ответ", "Возврат к обсуждению", "Отказ"],
    nextSteps: [
      "Очисти список контактов от отказов.",
      "Сверь сообщения с фактическими условиями.",
      "Выбери небольшую тестовую выборку.",
      "Отмечай только фактические ответы и дальнейшие действия.",
      "Сравни результаты и обнови шаблоны.",
    ],
  });
}

export function reactiveKitText(report: ReactiveReport) {
  return [
    "РеАктив AI — комплект для повторного контакта",
    "Сегменты", ...report.segments,
    "Варианты сообщений", ...report.messages.map((item) => `${item.segment} · ${item.goal} — ${item.text}`),
    "Календарь", ...[...report.schedule].sort((a, b) => a.day - b.day)
      .map((item) => `День ${item.day} — ${item.action} ${item.stopCondition}`),
    "Возражения", ...report.objections.map((item) => `${item.objection} — ${item.answer}`),
    "Предложения", ...report.offers,
    "Поля контроля", ...report.metrics,
    "Следующие шаги", ...report.nextSteps,
  ].join("\n");
}
