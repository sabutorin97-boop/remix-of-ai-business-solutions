function env(name: string): string | undefined {
  const v = process.env[name];
  return v && v.trim() ? v.trim() : undefined;
}

export interface PartnerTerms {
  commissionPercent: string;
  payout: string;
  managerContact: string;
  /** true, если условия не заданы в окружении и показываются заглушки. */
  isDefault: boolean;
}

export function partnerTerms(): PartnerTerms {
  const commissionPercent = env("PARTNER_COMMISSION_PERCENT");
  const payout = env("PARTNER_PAYOUT_TERMS");
  const managerContact = env("PARTNER_MANAGER_CONTACT");
  return {
    commissionPercent: commissionPercent ?? "20",
    payout: payout ?? "после того, как клиент оплатил проект и работа принята",
    managerContact: managerContact ?? "@ai_profigrup",
    isDefault: !commissionPercent || !payout,
  };
}

export function termsText(): string {
  const t = partnerTerms();
  const lines = [
    "💰 <b>Условия партнёрства</b>",
    "",
    `<b>Комиссия:</b> ${t.commissionPercent}% от суммы проекта.`,
    `<b>Когда платим:</b> ${t.payout}.`,
    `<b>Кто закрывает сделку:</b> студия. Ваша задача — найти бизнес с болью из каталога, поговорить, договориться о созвоне и передать контакт через кнопку «Передать клиента».`,
    `<b>За что отвечает студия:</b> расчёт стоимости, коммерческое предложение, договор, разработка, запуск, поддержка.`,
    `<b>Ваш клиент закреплён за вами</b> с момента передачи контакта через бот — так в системе видно, кто привёл.`,
    "",
    `<b>Вопросы по деньгам и спорным сделкам:</b> ${t.managerContact}`,
  ];
  if (t.isDefault) {
    lines.push(
      "",
      "⚠️ <i>Часть условий пока показана по умолчанию и не подтверждена компанией. Уточните процент и порядок выплат у руководителя, прежде чем что-то обещать клиенту.</i>",
    );
  }
  return lines.join("\n");
}

